// Dry-check helper for LM Market Bot v0.2.28 sell instruction.
//
// Mirrors addToken2022TransferHookAccountsForGmInstruction (post-fix) by
// building the ProcessInitializeSell keys from the GM IDL's processInitializeSell
// account list, in IDL order, using Anchor's CONST_ACCOUNTS defaults
// (tokenProgram = classic SPL Token, systemProgram, rent, associatedTokenProgram).
// Then runs the same base-keep / tail-append logic the bot uses.
//
// Run: node scripts/dry-check-carbon-sell.js

const { Connection, PublicKey } = require('@solana/web3.js');
const { baseIdl: gmBaseIdl } = require('@staratlas/factory/dist/marketplace/types/gmIdl');
const { getOrderVault, getMarketVars, getOpenOrdersCounter } = require('@staratlas/factory/dist/marketplace/pda_getters');
const anchor = require('@staratlas/anchor');
const {
  TOKEN_2022_PROGRAM_ID,
  TOKEN_PROGRAM_ID,
  unpackMint,
  getTransferHook,
  getExtraAccountMetaAddress,
} = require('@solana/spl-token');

const RPC_URL = process.env.RPC_URL || 'https://mainnet.helius-rpc.com/?api-key=61b4b51d-2ac1-4039-8b8f-5fe0a9a74cbe';
const GM_PROGRAM_ID = new PublicKey('traderDnaR5w6Tcoi3NFm53i48FTDNbGjBSZwWXDRrg');
const CARBON_CERT_MINT = new PublicKey('D3ashrcb3izVPfnSTUky6MRmNBJmjYx9oXhm5rb9k5SL');
const ATLAS_MINT = new PublicKey('ATLASXmbPQxBUYbxPsVEvusUaRfTR2LQ4Q8Rkp5S5kP');
const DUMMY_WALLET_PUBKEY = new PublicKey('3MKddH2YyuMgQL27f8id89RhfMyni8Bv5nhoGX4u2u2D');

function fmt(p) { return p.toBase58(); }
function findIdlIx(name) {
  const ix = gmBaseIdl.instructions.find((i) => i.name === name);
  if (!ix) throw new Error(`IDL is missing instruction ${name}`);
  return ix;
}

(async () => {
  const connection = new Connection(RPC_URL, 'confirmed');

  console.log('--- dry check: LM sell on live Carbon certificate mint ---');
  console.log('RPC:           ', RPC_URL);
  console.log('GM program:    ', fmt(GM_PROGRAM_ID));
  console.log('Carbon cert:   ', fmt(CARBON_CERT_MINT));
  console.log('ATLAS mint:    ', fmt(ATLAS_MINT));
  console.log('Wallet pubkey: ', fmt(DUMMY_WALLET_PUBKEY));

  // Derive PDAs we need for the IDL account list.
  const [marketVarsPda] = PublicKey.findProgramAddressSync(
    [Buffer.from('market-vars')],
    GM_PROGRAM_ID,
  );
  const [orderVaultPda] = getOrderVault(DUMMY_WALLET_PUBKEY, CARBON_CERT_MINT, GM_PROGRAM_ID);
  const [orderVaultAuthPda] = PublicKey.findProgramAddressSync(
    [Buffer.from('order-vault-auth'), DUMMY_WALLET_PUBKEY.toBuffer()],
    GM_PROGRAM_ID,
  );
  const [openOrdersCounterPda] = getOpenOrdersCounter(DUMMY_WALLET_PUBKEY, CARBON_CERT_MINT, GM_PROGRAM_ID);
  const [registeredCurrencyPda] = PublicKey.findProgramAddressSync(
    [Buffer.from('registered-currency'), ATLAS_MINT.toBuffer()],
    GM_PROGRAM_ID,
  );

  // Order account pubkey is generated by the bot on each new order; use a
  // dummy pubkey for the dry check (this is a key in the keys list, not
  // derived from anything, so a random pubkey is fine for shape verification).
  const orderAccountPk = anchor.web3.Keypair.generate().publicKey;

  // Build the account resolver for processInitializeSell by reading the IDL.
  // The bot's addToken2022TransferHookAccountsForGmInstruction only inspects /
  // mutates the `tokenProgram` key. To match what the bot sees, we replicate
  // Anchor's CONST_ACCOUNTS default for the unspecified slots.
  const sellIxIdl = findIdlIx('processInitializeSell');

  // PDAs derived from the wallet pubkey; we won't sign but the helper needs
  // these to know which keys are PDAs vs signer/regular.
  const SYSVAR_RENT_PUBKEY = anchor.web3.SYSVAR_RENT_PUBKEY;

  // Map IDL account names → the resolved pubkey.
  const idlAccountResolutions = {
    orderInitializer:                 DUMMY_WALLET_PUBKEY,
    marketVarsAccount:                marketVarsPda,
    depositMint:                      CARBON_CERT_MINT,
    receiveMint:                      ATLAS_MINT,
    orderVaultAccount:                orderVaultPda,
    orderVaultAuthority:              orderVaultAuthPda,
    initializerDepositTokenAccount:   DUMMY_WALLET_PUBKEY, // placeholder; Anchor doesn't validate
    initializerReceiveTokenAccount:   DUMMY_WALLET_PUBKEY,
    orderAccount:                     orderAccountPk,
    registeredCurrency:               registeredCurrencyPda,
    openOrdersCounter:                openOrdersCounterPda,
    systemProgram:                    anchor.web3.SystemProgram.programId,
    rent:                             SYSVAR_RENT_PUBKEY,
    tokenProgram:                     TOKEN_PROGRAM_ID, // Anchor CONST_ACCOUNTS default
  };

  // Build keys in IDL order.
  const keys = sellIxIdl.accounts.map((acc) => {
    const pubkey = idlAccountResolutions[acc.name];
    if (!pubkey) throw new Error(`No resolution for IDL account ${acc.name}`);
    return { pubkey, isSigner: !!acc.isSigner, isWritable: !!acc.isMut };
  });

  // === Mirror bot.ts addToken2022TransferHookAccountsForGmInstruction v0.2.28 ===
  const mintAccount = await connection.getAccountInfo(CARBON_CERT_MINT, 'confirmed');
  if (!mintAccount) throw new Error('Failed to fetch Carbon certificate mint account.');
  console.log('Cert mint owner:', fmt(mintAccount.owner),
    mintAccount.owner.equals(TOKEN_2022_PROGRAM_ID) ? '(Token-2022 ✓)' : '(NOT Token-2022 ✗)');

  if (mintAccount.owner.equals(TOKEN_2022_PROGRAM_ID)) {
    const mint = unpackMint(CARBON_CERT_MINT, mintAccount, TOKEN_2022_PROGRAM_ID);
    const transferHook = getTransferHook(mint);
    if (transferHook) {
      const keyCountBefore = keys.length;
      const extraAccountMetaList = await getExtraAccountMetaAddress(CARBON_CERT_MINT, transferHook.programId);
      const tail = [
        extraAccountMetaList,
        transferHook.programId,
        TOKEN_2022_PROGRAM_ID,
        new PublicKey('Sysvar1nstructions1111111111111111111111111'),
      ];
      for (const pubkey of tail) {
        if (!keys.some((k) => k.pubkey.equals(pubkey))) {
          keys.push({ pubkey, isSigner: false, isWritable: false });
        }
      }
      console.log('Appended tail accounts:', keys.length - keyCountBefore);
    } else {
      console.log('No transfer hook on cert; tail not appended.');
    }
  }
  // === End mirror ===

  console.log('---');
  console.log('Total accounts:', keys.length);
  console.log('Accounts (in instruction order):');
  keys.forEach((k, i) => {
    let label = '';
    if (k.pubkey.equals(TOKEN_PROGRAM_ID)) label = 'tokenProgram (classic SPL Token)';
    else if (k.pubkey.equals(TOKEN_2022_PROGRAM_ID)) label = 'tokenProgram (Token-2022)';
    else if (k.pubkey.equals(GM_PROGRAM_ID)) label = 'trader program (GM)';
    else if (k.pubkey.toBase58() === '11111111111111111111111111111111') label = 'system program';
    else if (k.pubkey.toBase58() === 'SysvarRent111111111111111111111111111111') label = 'rent sysvar';
    else if (k.pubkey.toBase58().startsWith('Sysv')) label = 'Sysvar1nstructions';
    else if (k.pubkey.toBase58().startsWith('AvSU')) label = 'extraAccountMetaList (transfer hook)';
    else if (k.pubkey.toBase58().startsWith('tHookm')) label = 'transfer hook program';
    else if (k.pubkey.toBase58() === fmt(CARBON_CERT_MINT)) label = 'Carbon cert mint';
    else if (k.pubkey.toBase58() === fmt(ATLAS_MINT)) label = 'ATLAS mint';
    else if (k.pubkey.toBase58() === fmt(DUMMY_WALLET_PUBKEY)) label = '(dummy initializer / acct)';
    else if (k.pubkey.toBase58() === fmt(marketVarsPda)) label = 'marketVarsAccount (PDA)';
    else if (k.pubkey.toBase58() === fmt(orderVaultPda)) label = 'orderVaultAccount (PDA)';
    else if (k.pubkey.toBase58() === fmt(orderVaultAuthPda)) label = 'orderVaultAuthority (PDA)';
    else if (k.pubkey.toBaseString?.() === fmt(orderAccountPk)) label = '(dummy order account)';
    else if (k.pubkey.toBase58() === fmt(registeredCurrencyPda)) label = 'registeredCurrency (PDA)';
    else if (k.pubkey.toBase58() === fmt(openOrdersCounterPda)) label = 'openOrdersCounter (PDA)';
    console.log(`  [${String(i).padStart(2)}] ${fmt(k.pubkey)}  ${label}`);
  });

  // Verification.
  const expectedTailLabels = ['extraAccountMetaList', 'transfer hook program', 'Token-2022', 'Sysvar1nstructions'];
  const tailSlice = keys.slice(-4).map((k) => {
    if (k.pubkey.equals(TOKEN_2022_PROGRAM_ID)) return 'Token-2022';
    if (k.pubkey.toBase58().startsWith('AvSU')) return 'extraAccountMetaList';
    if (k.pubkey.toBase58().startsWith('tHookm')) return 'transfer hook program';
    if (k.pubkey.toBase58().startsWith('Sysv')) return 'Sysvar1nstructions';
    return '?';
  });
  const tailOk = expectedTailLabels.every((lbl, i) => tailSlice[i] === lbl);

  const baseRegion = keys.slice(0, keys.length - 4);
  const baseTokenProgram = baseRegion.find((k) => k.pubkey.equals(TOKEN_PROGRAM_ID) || k.pubkey.equals(TOKEN_2022_PROGRAM_ID));
  const baseOk = !!baseTokenProgram && baseTokenProgram.pubkey.equals(TOKEN_PROGRAM_ID);

  // All token-program-shaped keys in the full list (should be exactly 2: classic in base, Token-2022 in tail).
  const allTokenProgramSlots = keys
    .map((k, i) => ({ k, i }))
    .filter(({ k }) => k.pubkey.equals(TOKEN_PROGRAM_ID) || k.pubkey.equals(TOKEN_2022_PROGRAM_ID));

  console.log('---');
  console.log('Expected tail order:', expectedTailLabels.join(' | '));
  console.log('Actual tail order:  ', tailSlice.join(' | '));
  console.log('Tail order match:   ', tailOk ? 'OK ✓' : 'MISMATCH ✗');
  console.log('Base tokenProgram:  ', baseTokenProgram ? fmt(baseTokenProgram.pubkey) : 'missing',
    baseTokenProgram && baseTokenProgram.pubkey.equals(TOKEN_PROGRAM_ID) ? '(classic ✓)' : '✗');
  console.log('All token-program keys:');
  allTokenProgramSlots.forEach(({ i, k }) => {
    console.log(`  [${i}] ${fmt(k.pubkey)} (${k.pubkey.equals(TOKEN_PROGRAM_ID) ? 'classic' : 'Token-2022'})`);
  });
  const totalOk = keys.length === 18;
  console.log('Total account count:', keys.length, totalOk ? '(18 ✓ — matches manual MRZ-20 Carbon LM tx 39Ju7m…)' : '(expected 18)');
  console.log('---');
  if (tailOk && baseOk && totalOk) {
    console.log('RESULT: PASS — base tokenProgram stays classic, 4-account tail appended in v0.1.21 order, total 18 accts.');
    process.exit(0);
  } else {
    console.log('RESULT: FAIL — shape does not match expected v0.1.21 reference.');
    process.exit(1);
  }
})().catch((err) => {
  console.error('Dry check errored:', err && err.stack ? err.stack : err);
  process.exit(1);
});
